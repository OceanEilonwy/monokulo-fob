"""Draws the Fob seal and writes every file that carries it.

The mark is the Monokulo iris pressed into a disc of orange wax (the "Calm
edge" pour). Its edge is one formula, `wax_radius`; FobMark in
android/.../ui/Components.kt draws from the same formula, so change both
together.

Run from the repository root after changing anything here:

    python3 docs/brand/seal.py

The wordmark needs fontTools (`pip install fonttools`) to outline the f and the
b from the app's own Manrope at weight 800.
"""

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android/app/src/main/res"
BRAND = ROOT / "docs/brand"

ORANGE = "#FF6600"
DEEP = "#C24E00"
INK = "#1A1917"
PAPER = "#F4F1EA"

# The seal lives in a 100 x 100 box centred on 50,50.
STEPS = 120
RING_R, RING_W = 29.0, 3.2
IRIS = 2.05  # scale of the Monokulo iris, drawn around 0,0 at its own size

# The six iris blades and the hex between them, from the Monokulo lens.
BLADES = [
    [(0, -5), (4.33, -2.5), (5.5, -9.53)],
    [(4.33, -2.5), (4.33, 2.5), (11, 0)],
    [(4.33, 2.5), (0, 5), (5.5, 9.53)],
    [(0, 5), (-4.33, 2.5), (-5.5, 9.53)],
    [(-4.33, 2.5), (-4.33, -2.5), (-11, 0)],
    [(-4.33, -2.5), (0, -5), (-5.5, -9.53)],
]
HEX = [(0, -5), (4.33, -2.5), (4.33, 2.5), (0, 5), (-4.33, 2.5), (-4.33, -2.5)]

# Wordmark spacing, in em. The f gets more room than the b: its crossbar points
# straight at the seal, so equal gaps look tight on that side.
GAP_F = 0.125
GAP_B = 0.1
SEAL_X_HEIGHTS = 1.24  # seal height as a multiple of the x-height


def wax_radius(t):
    return 39.5 + 1.7 * math.sin(5 * t + 0.4) + 0.6 * math.sin(9 * t + 1)


def wax_points():
    pts = []
    for i in range(STEPS):
        t = i / STEPS * 2 * math.pi
        r = wax_radius(t)
        pts.append((50 + math.cos(t) * r, 50 + math.sin(t) * r))
    return pts


def n(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def poly(pts):
    return "M" + "L".join(f"{n(x)},{n(y)}" for x, y in pts) + "Z"


def iris(shape):
    return poly([(50 + x * IRIS, 50 + y * IRIS) for x, y in shape])


def circle(r):
    """A circle as two arcs, which both SVG and Android vectors accept."""
    return f"M{n(50 - r)},50a{n(r)},{n(r)} 0 1 0 {n(2 * r)},0a{n(r)},{n(r)} 0 1 0 {n(-2 * r)},0Z"


def bbox(pts):
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs) - min(xs), max(ys) - min(ys)


WAX = poly(wax_points())
BLADES_D = "".join(iris(b) for b in BLADES)
HEX_D = iris(HEX)

# One colour: the wax with the ring and the blades cut through, the hex left
# standing. Even-odd: the ring's outer circle cuts, its inner circle fills back.
CUT = WAX + circle(RING_R + RING_W / 2) + circle(RING_R - RING_W / 2) + BLADES_D


def svg_layers():
    return (
        f'<path fill="{ORANGE}" d="{WAX}"/>'
        f'<path fill="none" stroke="{DEEP}" stroke-width="{n(RING_W)}" d="{circle(RING_R)}"/>'
        f'<path fill="{DEEP}" d="{BLADES_D}"/>'
        f'<path fill="{INK}" d="{HEX_D}"/>'
    )


def vector(comment, size, viewport, group, paths):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by docs/brand/seal.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <group {group}>
{paths}
    </group>
</vector>
"""


def fit(viewport, diameter):
    """Group attributes that scale the 100 box so the wax is `diameter` across, centred."""
    _, _, w, h = bbox(wax_points())
    k = diameter / max(w, h)
    t = viewport / 2 - 50 * k
    return f'android:translateX="{n(t)}" android:translateY="{n(t)}" android:scaleX="{k:.4f}" android:scaleY="{k:.4f}"'


def colour_paths():
    return "\n".join([
        f'        <path android:fillColor="{ORANGE}" android:pathData="{WAX}" />',
        f'        <path android:strokeColor="{DEEP}" android:strokeWidth="{n(RING_W)}" android:pathData="{circle(RING_R)}" />',
        f'        <path android:fillColor="{DEEP}" android:pathData="{BLADES_D}" />',
        f'        <path android:fillColor="{INK}" android:pathData="{HEX_D}" />',
    ])


def cut_path(colour):
    return f'        <path android:fillColor="{colour}" android:fillType="evenOdd" android:pathData="{CUT}" />'


def wordmark(letters):
    """`fob` with the seal as the o, Manrope ExtraBold outlined, 100 units to the em."""
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    font = instantiateVariableFont(TTFont(RES / "font/manrope.ttf"), {"wght": 800})
    upm = font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    glyf = font["glyf"]

    def ink(ch):
        g = glyf[cmap[ord(ch)]]
        g.recalcBounds(glyf)
        return g.xMin / upm, g.yMin / upm, g.xMax / upm, g.yMax / upm

    def outline(ch, x):
        pen = SVGPathPen(glyphs, ntos=n)
        # font units, y up, to wordmark units (100 per em), y down, baseline at 0
        glyphs[cmap[ord(ch)]].draw(TransformPen(pen, (100 / upm, 0, 0, -100 / upm, x * 100, 0)))
        return pen.getCommands()

    f_left, _, f_right, f_top = ink("f")
    b_lsb, b_bottom, b_right, _ = ink("b")
    x_height = ink("x")[3]

    bx, by, bw, bh = bbox(wax_points())
    seal_h = SEAL_X_HEIGHTS * x_height
    k = seal_h / bh * 100  # 100 box units to wordmark units
    seal_left = f_right + GAP_F
    seal_w = bw * k / 100
    b_origin = seal_left + seal_w + GAP_B - b_lsb
    seal_top = -(x_height / 2 + seal_h / 2)
    tx = seal_left * 100 - bx * k
    ty = seal_top * 100 - by * k

    left, right = f_left * 100, (b_origin + b_right) * 100
    top = min(-f_top, seal_top) * 100
    bottom = max(-b_bottom, seal_top + seal_h) * 100
    pad = 4
    view = f"{n(left - pad)} {n(top - pad)} {n(right - left + 2 * pad)} {n(bottom - top + 2 * pad)}"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" role="img" aria-label="fob">
<path fill="{letters}" d="{outline("f", 0)}"/>
<g transform="translate({n(tx)} {n(ty)}) scale({k:.5f})">{svg_layers()}</g>
<path fill="{letters}" d="{outline("b", b_origin)}"/>
</svg>
"""


def main():
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector(
        "The Fob seal: the Monokulo iris pressed into orange wax, inside the\n     adaptive icon's 66 dp safe zone.",
        108, 108, fit(108, 60), colour_paths()))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector(
        "The Fob seal in one colour for themed icons: the ring and blades are\n     cut through the wax, the hex stands.",
        108, 108, fit(108, 60), cut_path("#FF000000")))
    (RES / "drawable/ic_stat_fob.xml").write_text(vector(
        "The Fob seal in one colour, for the status bar.",
        24, 24, fit(24, 21), cut_path("#FFFFFFFF")))

    BRAND.mkdir(exist_ok=True)
    x, y, w, h = bbox(wax_points())
    view = f"{n(x)} {n(y)} {n(w)} {n(h)}"
    (BRAND / "fob-mark.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" role="img" aria-label="Fob">{svg_layers()}</svg>\n')
    (BRAND / "fob-mark-mono.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" role="img" aria-label="Fob"><path fill-rule="evenodd" fill="{INK}" d="{CUT}"/></svg>\n')
    (BRAND / "fob-wordmark.svg").write_text(wordmark(INK))
    (BRAND / "fob-wordmark-on-dark.svg").write_text(wordmark(PAPER))


if __name__ == "__main__":
    main()
